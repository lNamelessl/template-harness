// src/approver.js — approval: generates the full playbook-aware implementation prompt
// artifact (STATUS.md-referencing format), saves it to DB + volume, pushes Telegram.
// AUTO_BUILD stays a disabled v1.1 stub by design.
'use strict';
const fs = require('fs');
const path = require('path');
const config = require('./config');
const { ideaStmts, now } = require('./db');
const { pushTelegram } = require('./telegram');

const EASE_BLOCK = `EASE-OF-USE REQUIREMENTS (binding):
1. Deploy form: ZERO required prompts; at most ONE (a single user-owned credential, description phrased as an instruction with its exact source URL).
2. Every generated secret/credential: defaultValue = \${{secret(24)}} (or base64/hex variants); NEVER literals — bake literals into startCommand instead.
3. Never prompt for PORT, domains, TCP-proxy hosts, DB URLs, or anything derivable at runtime (use \${{Ref.VAR}} / RAILWAY_* / baked defaults like \${MEMORY:-4G}).
4. Missing-credential state = guided state: setup page (200, healthy) + loud deploy-log banner naming the exact next action; setting it auto-recovers; no crash loops.
5. First login self-served: per-deploy creds in deploy logs under a loud banner AND on the volume; marker-guarded seed that never re-fires; banner says change-it-now.
6. Healthcheck-gate every service: dotless, unauth, 2xx route; targetPort pinned; volume paths don't shadow app dirs; secret-bearing paths deny-all.
7. User-facing errors = plain cause + exact next action + link; typed envelopes for anticipated failures; no raw tracebacks outside logs.
8. Unconfigured→connecting→ready progress visible; recovery from degraded/reclaimed is one click.
9. Listing: pitch + deploy button above the fold; numbered ≤5-step "after deploying" quickstart; per-credential sourcing table; measured honest-limits table; the six validator headings exactly, unwrapped.
10. Verify 2/2 fresh deploys FROM the published template (railway init first, </dev/null) exercising the zero-prompt path end to end.`;

function buildImplementationPrompt(idea) {
  const report = idea.report ? JSON.parse(idea.report) : {};
  const demand = idea.demand ? JSON.parse(idea.demand) : {};
  const sources = JSON.parse(idea.sources || '[]');
  const rating = idea.rating || report.rating || '?';
  const slug = report.suggested_name_slug || `${idea.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40)} (slug ≤40)`;

  const lines = [];
  lines.push(`# ${idea.name} — Implementation Prompt`);
  lines.push('');
  lines.push(`*Generated by Template Idea Harness ${now().slice(0, 10)} · verdict: ${report.verdict || 'n/a'} · rating: ${'★'.repeat(Number(rating) || 0)} (${rating}/5) · confidence: ${report.confidence || 'n/a'}*`);
  lines.push('');
  lines.push('## Failure/evidence context (why this idea won)');
  lines.push('');
  lines.push(`- Demand: ${report.demand || (demand.stars ? `${demand.stars} GitHub stars` : 'n/a')}`);
  lines.push(`- Coverage check vs marketplace: ${report.coverage_check || 'n/a'}`);
  lines.push(`- Competitor scan: ${report.competitor_scan || 'n/a'}`);
  lines.push(`- Uniqueness: ${report.uniqueness || 'n/a'}`);
  lines.push(`- ToS/legal flags: ${report.tos_legal_flags || 'none found'}`);
  lines.push(`- Discovery sources: ${sources.join(', ') || 'n/a'}${demand.url ? ` · ${demand.url}` : ''}`);
  lines.push(`- Risks: ${report.risks || 'n/a'}`);
  lines.push('');
  lines.push('## Key requirements');
  lines.push('');
  lines.push('| Item | Value |');
  lines.push('|---|---|');
  lines.push(`| Stack | your choice — justify in the build |`);
  lines.push(`| Suggested listing name | ${report.suggested_name_slug || idea.name} |`);
  lines.push(`| Effort sketch | ${report.implementation_sketch || 'n/a'} |`);
  lines.push('| Ops | /health dotless unauth; keyless boot healthy; healthcheck gate; ON_FAILURE/10; pins everywhere |');
  lines.push('');
  lines.push('## Steps 0–5');
  lines.push('');
  lines.push('0. **Spike (zero deploys)** — prove the risky parts offline first (image boot, core loop, auth) before any Railway deploy.');
  lines.push('1. **Scaffold** — repo via github-repo-setup; structure per the build prompt conventions; Dockerfile non-root + pinned base; railway.json relative dotless healthcheck (quirk 60b form).');
  lines.push('2. **Creator deploy + structural battery** — `railway init` FIRST (quirk 40a) → deploy → health → gate 401/200 → UI battery in-container.');
  lines.push('3. **Live battery** — real credentials end to end (typed envelopes, upstream hygiene); Puppeteer battery where a UI exists.');
  lines.push('4. **Publish** — serializedConfig audit (zero accidental literal→prompt conversions; DEEPSEEK_API_KEY-style required-no-default only for user-owned credentials) → `railway templates create` → publish with README → **2/2 fresh deploys FROM the published template** (`railway init` first, `MSYS_NO_PATHCONV=1`, `</dev/null`; healthcheck SUCCESS + gate + guided state each) → throwaways deleted, creator kept.');
  lines.push('5. **STATUS.md** — fresh re-read immediately before writing; new row + quirks (record any deltas found).');
  lines.push('');
  lines.push('## Acceptance criteria');
  lines.push('');
  lines.push('- [ ] Published template live; 2/2 fresh deploys zero-prompt succeed');
  lines.push('- [ ] Healthcheck-gated; guided no-credential state healthy; typed error envelopes');
  lines.push('- [ ] Full battery green (structural + live + UI)');
  lines.push('- [ ] EASE-OF-USE block satisfied end to end; honest-limits + sourcing tables in listing');
  lines.push('');
  lines.push(EASE_BLOCK);
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('Write the full implementation prompt following the house playbook (`harness-prompts/` style: verdict line, failure/evidence context, key-requirements table, Steps 0–5 incl. publish pipeline + 2/2 verification, acceptance criteria, the EASE-OF-USE block verbatim). Then execute it.');
  lines.push('');
  lines.push(`Project name: keep it short (≤18 chars) e.g. "${idea.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 18)}". Template slug: "${slug}".`);
  return lines.join('\n');
}

async function approveIdea(ideaId) {
  const idea = ideaStmts.byId.get(ideaId);
  if (!idea) throw new Error('idea not found');
  if (!['READY', 'RESEARCH_FAILED', 'DISMISSED', 'NEW'].includes(idea.status)) {
    if (idea.status === 'APPROVED') return { already: true };
  }
  const promptMd = buildImplementationPrompt(idea);
  const dir = path.join(config.dataDir, 'artifacts', String(ideaId));
  fs.mkdirSync(dir, { recursive: true });
  const p = path.join(dir, 'implementation-prompt.md');
  fs.writeFileSync(p, promptMd);

  let artifacts = [];
  try { artifacts = JSON.parse(idea.artifacts || '[]'); } catch (e) { artifacts = []; }
  const entry = {
    name: 'implementation-prompt.md',
    path: `/api/ideas/${ideaId}/artifacts/${encodeURIComponent('implementation-prompt.md')}`,
    bytes: Buffer.byteLength(promptMd),
    created_at: now(),
  };
  const idx = artifacts.findIndex((a) => a.name === entry.name);
  if (idx >= 0) artifacts[idx] = entry; else artifacts.push(entry);

  ideaStmts.approve.run('APPROVED', now(), JSON.stringify(artifacts), ideaId);

  const tg = await pushTelegram(`✅ idea approved — implementation prompt ready: ${idea.name}\n${promptMd.split('\n').length} lines, download from the harness UI (workspace files panel).`);
  const logLine = `${now()} approved → prompt generated (${entry.bytes} B) → telegram: ${tg.pushed ? 'SENT' : `NOT SENT (${tg.reason})`}`;
  let dlog = '';
  try {
    const cur = ideaStmts.byId.get(ideaId).dispatch_log;
    dlog = cur ? `${cur}\n${logLine}` : logLine;
    const lines = dlog.split('\n');
    if (lines.length > 50) dlog = lines.slice(-50).join('\n');
  } catch (e) { dlog = logLine; }
  ideaStmts.appendDispatch.run(dlog, ideaId);
  return { approved: true, telegram: tg, artifact: entry };
}

module.exports = { approveIdea, buildImplementationPrompt, EASE_BLOCK };
